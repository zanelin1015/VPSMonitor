import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import ts from 'typescript'

const source = await readFile(new URL('../src/components/AgentDetailPanel.tsx', import.meta.url), 'utf8')
const ast = ts.createSourceFile('AgentDetailPanel.tsx', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
let columns
const rows = new Map()
function visit(node) {
  if (ts.isVariableDeclaration(node) && node.name.getText(ast) === 'clientColumns') columns = node.initializer
  if (ts.isJsxElement(node)) {
    const attribute = node.openingElement.attributes.properties.find(item => item.name?.getText(ast) === 'className')
    if (attribute?.initializer && ts.isStringLiteral(attribute.initializer)) rows.set(attribute.initializer.text, node)
  }
  ts.forEachChild(node, visit)
}
visit(ast)
assert.ok(columns && ts.isArrayLiteralExpression(columns))
const clientColumnSource = columns.elements.map(node => node.getText(ast)).join('\n')
const firstColumn = columns.elements[0].getText(ast)
assert.match(firstColumn, /key: 'client'/)
assert.match(firstColumn, /fixed: 'left'/, 'client identity stays pinned when scrolling')
const billing = columns.elements.find(node => /key: 'billing'/.test(node.getText(ast))).getText(ast)
assert.match(billing, /title: '配置信息'/)
assert.match(billing, /width: 250/, 'billing summary is compact')
assert.doesNotMatch(billing, /<InputNumber|<Select|onSaveClientBilling/, 'billing rows display summaries without inline save controls')
assert.match(source, /<XUIClientConfigModal/, 'one editor handles all client configuration')
const traffic = columns.elements.find(node => /key: 'traffic'/.test(node.getText(ast))).getText(ast)
assert.match(traffic, /title: '流量'/)
assert.match(traffic, /↑|↓/)
assert.doesNotMatch(traffic, /<InputNumber|XUIClientTrafficResetEditor/, 'traffic row is read-only')
assert.ok(!columns.elements.some(node => /key: 'expiry'/.test(node.getText(ast))), 'time summary shares the configuration column')
assert.match(source, /tableLayout="fixed"[\s\S]*scroll=\{\{ x: 'max-content' \}\}/, 'table scroll width is measured by rc-table')
const css = await readFile(new URL('../src/styles/agent-rail.css', import.meta.url), 'utf8')
const baseCSS = await readFile(new URL('../src/styles/base.css', import.meta.url), 'utf8')
const dashboardCSS = await readFile(new URL('../src/styles/dashboard.css', import.meta.url), 'utf8')
const workspaceCSS = await readFile(new URL('../src/styles/workspace.css', import.meta.url), 'utf8')
assert.match(css, /\.agent-list \.ant-spin-nested-loading\s*\{[^}]*overflow-x: hidden;[^}]*overscroll-behavior-x: none;/, 'card lists cannot pan or rubber-band horizontally')
assert.match(css, /\.agent-list-list \.ant-spin-nested-loading\s*\{[^}]*overflow-x: auto;/, 'wide row mode retains its own horizontal viewport')
assert.match(css, /\.xui-client-table \.ant-table-content\s*\{[^}]*overflow-x: auto !important;[^}]*overscroll-behavior-x: none(?: !important)?;/, 'client table can scroll internally without horizontal rebound')
assert.match(baseCSS, /\.workspace-grid-agent-open \.tabs-card \.ant-tabs-content-holder\s*\{[^}]*overscroll-behavior-x: none;/, 'agent detail outer scroller cannot rebound horizontally')
assert.match(css, /\.client-billing-controls\s*\{[^}]*display: grid;[^}]*gap: 6px;/)
assert.match(css, /\.xui-client-table \.ant-table-cell-fix-left\s*\{[^}]*z-index: 5;/, 'compact inputs cannot paint over the pinned column')
assert.match(source, /key: 'actions',[\s\S]*?width: restrictedView \? 230 : 240,[\s\S]*?fixed: 'right'/, 'client actions stay together in one compact fixed column')
assert.match(source, /className="client-action-controls"[\s\S]*?onCopyImportURL[\s\S]*?onOpenImportURL[\s\S]*?onAuthorizeCustomer[\s\S]*?onDeleteXUIClient/, 'client import, authorization and delete actions share one renderer')
assert.match(source, /className="outbound-head-meta"/, 'outbound relation tags have a constrained wrapper')
assert.doesNotMatch(clientColumnSource, /key: 'import'/, 'client import is not rendered as a separate column')
assert.doesNotMatch(clientColumnSource, /key: 'customer'/, 'client authorization is not rendered as a separate column')
assert.match(css, /\.xui-client-table \.ant-table-cell-fix-right\s*\{[^}]*z-index: 5;/, 'right action columns paint above scrolling cells')
assert.match(baseCSS, /\.admin-content-page\s*\{[\s\S]*?overflow-x: clip;[\s\S]*?overflow-y: auto;/, 'admin pages keep horizontal scrolling inside each table')
assert.match(baseCSS, /\.admin-content-page \.ant-table-content,[\s\S]*?overflow-x: auto;[\s\S]*?overflow-y: hidden;/, 'all admin tables own their horizontal scroll viewport')
assert.match(baseCSS, /\.workspace-grid-agent-open \.tabs-card \.ant-tabs-content-holder\s*\{[\s\S]*?overflow-x: clip;[\s\S]*?overflow-y: auto;/, 'agent tabs do not compete with table horizontal scrolling')
assert.match(dashboardCSS, /\.admin-workbench-page\s*\{[\s\S]*?overflow-x: clip;[\s\S]*?overflow-y: auto;/, 'responsive dashboard keeps horizontal scrolling inside tables')
assert.match(workspaceCSS, /\.ant-table-wrapper\s*\{\s*overflow-x: clip;/, 'small-screen table wrappers do not become a second scrollport')
assert.match(workspaceCSS, /\.ant-table-wrapper \.ant-table-content\s*\{[\s\S]*?overflow-x: auto;[\s\S]*?overscroll-behavior-x: contain;/, 'small-screen tables keep touch scrolling on the table content')
assert.match(dashboardCSS, /\.ant-table-wrapper\s*\{\s*overflow-x: clip;/, 'dashboard table wrappers do not become a second scrollport')
assert.match(dashboardCSS, /\.outbound-head\s*\{[^}]*flex-wrap: wrap;/, 'outbound card headers wrap long relation tags')
assert.match(dashboardCSS, /\.outbound-head-meta \.ant-tag\s*\{[^}]*white-space: normal;/, 'outbound relation tags can break long names')
assert.match(dashboardCSS, /\.outbound-tag\s*\{[^}]*overflow-wrap: anywhere;/, 'outbound names can break long words')
assert.match(css, /\.client-billing-cycle-row\s*\{[^}]*flex-wrap: nowrap;[^}]*white-space: nowrap;/)
assert.match(css, /\.client-billing-cycle-row > \*\s*\{[^}]*flex: 0 0 auto;/)
console.log('client fixed columns, traffic arrows and unified editor layout safeguards passed')
